import { STUDIO_TZ, matchesStudioTz } from "@/lib/calendar";

/**
 * Виконується один раз при старті сервера, до першого запиту.
 *
 * Єдина задача — зафіксувати часову зону процесу. Календар, «Сьогодні» та
 * аналітика рахують дні через `getHours`/`getDate`, тобто в зоні процесу.
 * Локально це Київ, а на Vercel — UTC, і різниця не абстрактна: щовечора
 * після 21:00 (взимку після 22:00) сервер вважає, що досі вчора. Екран
 * «Сьогодні» показував би вчорашній список, а тижнева виручка різалась би
 * по межі UTC і частково їхала в сусідній період.
 *
 * `TZ` виставляємо тут, а не лише у змінних Vercel, бо забута змінна повертає
 * той самий баг мовчки — без падіння й без сліду в логах.
 */
export function register() {
  process.env.TZ ??= STUDIO_TZ;

  // Зона могла бути задана ззовні (Vercel, Docker, локальний .env). Якщо вона
  // не збігається зі студійною — попереджаємо, але не падаємо: несправедливо
  // класти сайт через налаштування, яке ламає лише адмінку.
  if (!matchesStudioTz()) {
    console.warn(
      `[kotova-taping] Часова зона процесу (${process.env.TZ ?? "системна"}) ` +
        `не збігається зі студійною (${STUDIO_TZ}). Календар і аналітика ` +
        "рахуватимуть добу за чужою зоною — задайте TZ=" +
        STUDIO_TZ,
    );
  }
}
