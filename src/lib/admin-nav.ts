/**
 * Розділи адмінки — одним списком для обох навігацій.
 *
 * До цього таб-бар і десктопне меню тримали власні копії, і вони розійшлись:
 * той самий `/admin/calendar` звався «Записи» внизу й «Календар» угорі, а
 * порядок розділів не збігався. Людина вчиться розташуванню пунктів, і коли
 * воно міняється разом із шириною екрана, вчитись нема чому.
 *
 * Іконок тут немає навмисно: вони потрібні лише таб-бару, а тягнути JSX у
 * модуль, який імпортує і серверний код, означало б робити його клієнтським.
 */

export type AdminSection = {
  href: string;
  label: string;
  /**
   * Чи показувати в нижньому таб-барі телефона.
   *
   * Місць там п'ять — більше не влазить у рядок, не перетворивши підписи на
   * нечитабельні. Решта живе за кнопкою «Ще».
   */
  primary: boolean;
};

/**
 * Порядок — за частотою в роботі: день починається з «Сьогодні», далі записи
 * й заявки, потім графік. Прайс і аналітика відкриваються раз на тиждень, тож
 * стоять останніми й у таб-бар не потрапляють.
 */
export const ADMIN_SECTIONS: AdminSection[] = [
  { href: "/admin", label: "Сьогодні", primary: true },
  { href: "/admin/calendar", label: "Записи", primary: true },
  { href: "/admin/requests", label: "Заявки", primary: true },
  { href: "/admin/clients", label: "Клієнти", primary: true },
  // Графік проставляють постійно — щодня або щотижня наперед. Набори
  // замовляють помітно рідше, тож у таб-барі місце дістається графіку.
  { href: "/admin/schedule", label: "Графік", primary: true },
  { href: "/admin/kits", label: "Набори", primary: false },
  { href: "/admin/services", label: "Прайс", primary: false },
  { href: "/admin/analytics", label: "Аналітика", primary: false },
];

/**
 * Чи цей розділ зараз відкритий.
 *
 * «Сьогодні» — лише точний збіг: `startsWith("/admin")` підсвічував би його
 * на кожному екрані адмінки.
 */
export function isActiveSection(href: string, pathname: string): boolean {
  return href === "/admin" ? pathname === "/admin" : pathname.startsWith(href);
}
