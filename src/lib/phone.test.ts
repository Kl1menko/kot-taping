import assert from "node:assert/strict";
import { test } from "node:test";

import {
  formatPhone,
  isValidPhone,
  normalizePhone,
  phoneMatches,
} from "./phone.ts";

test("той самий номер у різних формах зводиться до одного", () => {
  // Це основа впізнавання клієнта: unique-індекс на clients.phone спрацює
  // лише тоді, коли всі ці варіанти дадуть однаковий рядок.
  for (const raw of [
    "0976663344",
    "+380976663344",
    "380976663344",
    "80976663344",
    "097 666 33 44",
    "+38 (097) 666-33-44",
    "  0976663344  ",
    "097-666-33-44",
  ]) {
    assert.equal(normalizePhone(raw), "0976663344", `не зведено: ${raw}`);
  }
});

test("номер без +380 приймається нарівні з міжнародним", () => {
  // Люди частіше пишуть саме так, і форма не має цього відкидати.
  assert.ok(isValidPhone("0976663344"));
  assert.ok(isValidPhone("+380976663344"));
  assert.ok(isValidPhone("097 666 33 44"));
});

test("неповний номер не проходить", () => {
  for (const raw of ["09766633", "097", "", "   ", "+380"]) {
    assert.ok(!isValidPhone(raw), `пройшло: ${raw}`);
  }
});

test("зайві цифри не проходять", () => {
  assert.ok(!isValidPhone("09766633445"));
  assert.ok(!isValidPhone("3809766633445"));
});

test("номер не з нуля після нормалізації відхиляється", () => {
  // Іноземний номер зводиться до самих цифр і не має вигляду 0XXXXXXXXX.
  assert.ok(!isValidPhone("+48123456789"));
});

test("показ завжди в міжнародному вигляді", () => {
  assert.equal(formatPhone("0976663344"), "+380 97 666 33 44");
  assert.equal(formatPhone("+380976663344"), "+380 97 666 33 44");
});

test("нерозпізнане показуємо як є, а не ламаємо", () => {
  // У базі може лежати старий запис із чимось нестандартним — краще показати
  // його дослівно, ніж зрізати до невпізнаваного вигляду.
  assert.equal(formatPhone("невідомо"), "невідомо");
  assert.equal(formatPhone("09766633"), "09766633");
});

test("пошук знаходить за хвостом номера", () => {
  // Майстриня пам'ятає останні цифри, а не номер цілком.
  assert.ok(phoneMatches("0976663344", "3344"));
  assert.ok(phoneMatches("0976663344", "666"));
  assert.ok(phoneMatches("0976663344", "+380976663344"));
  assert.ok(!phoneMatches("0976663344", "9999"));
});

test("порожній запит нічого не знаходить", () => {
  // Інакше порожнє поле пошуку показувало б усю базу як «збіг».
  assert.ok(!phoneMatches("0976663344", ""));
  assert.ok(!phoneMatches("0976663344", "   "));
});
