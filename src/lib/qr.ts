import "server-only";

import QRCode from "qrcode";

/**
 * QR-код на сторінку оплати.
 *
 * Малюється на сервері й передається в адмінку готовим рядком SVG. Причина —
 * не економія: екрани адмінки клієнтські, і бібліотека кодування (близько
 * 50 КБ) інакше поїхала б у бандл заради картинки, яка після створення
 * рахунку вже не змінюється.
 *
 * SVG, а не PNG: код лишається різким на будь-якому екрані, важить менше й
 * не потребує canvas.
 */
export async function paymentQrSvg(url: string): Promise<string> {
  return QRCode.toString(url, {
    type: "svg",
    // `margin` рахується в модулях, не пікселях. Одиниця — мінімальна «тиха
    // зона», яку сканери впевнено читають; нуль ламає розпізнавання.
    margin: 1,
    width: 220,
    // Середній рівень корекції: код лишається читабельним під відблиском на
    // екрані телефона й не роздувається зайвими модулями.
    errorCorrectionLevel: "M",
    color: { dark: "#111111", light: "#ffffff" },
  });
}
