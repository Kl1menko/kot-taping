"use client";

import { useRealtimeRefresh } from "@/lib/realtime";

/**
 * Тримає відкриту адмінку свіжою: заявка з сайту або зміна з іншого пристрою
 * з'являється сама, без F5.
 *
 * Живе в layout, тобто одна підписка на всю адмінку, а не по одній на екран:
 * сокетів було б стільки, скільки вкладок × екранів, а користі — та сама.
 * Нічого не рендерить.
 *
 * Перелічуємо всі таблиці, бо layout спільний для всіх сторінок. Зайве
 * оновлення тут дешеве — сторінка й так серверна.
 */
export function LiveRefresh() {
  useRealtimeRefresh(["appointments", "requests", "clients", "services"]);
  return null;
}
