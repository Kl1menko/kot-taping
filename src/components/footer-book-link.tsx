"use client";

import { useBookingModal } from "./booking-modal";

/**
 * «Записатись» у футері.
 *
 * Раніше тут стояло посилання на `/#booking`. Воно було правильним, поки за
 * тим якорем лежала сама анкета, — але форма переїхала в модальне вікно, і
 * секція `#booking` перетворилась на заклик із кнопкою. Виходило два кліки
 * замість одного: доїхати до низу лендінгу й натиснути там ще раз.
 *
 * З внутрішньої сторінки було гірше: клік перекидав людину з категорії чи
 * міста на головну — тобто виглядав як зламаний. Тепер поведінка та сама, що в
 * кнопок на картках і в липкій кнопці на телефоні: анкета відкривається на
 * місці, не забираючи людину зі сторінки, яку вона читає.
 *
 * Окремий клієнтський компонент, а не `"use client"` на весь футер: решта
 * футера — карта сайту зі статичних посилань, і її HTML має лишатись у
 * серверному рендері, бо саме по ній краулер розходиться по категоріях.
 */
export function FooterBookLink() {
  const { open } = useBookingModal();

  return (
    <button
      type="button"
      onClick={() => open()}
      className="cursor-pointer text-ink-muted underline-offset-4 transition-colors duration-200 hover:text-ink hover:underline"
    >
      Записатись
    </button>
  );
}
