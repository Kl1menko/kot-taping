-- Англійські назви й описи для послуг та наборів.
--
-- Сайт став двомовним: «/» українська, «/en» англійська. Прайс приходить із
-- бази, тож без цих колонок англійська версія показувала б українські назви
-- послуг посеред англійського тексту.
--
-- Окремі колонки, а не окрема таблиця перекладів: мов рівно дві й третьої не
-- планується, а join заради двох полів ускладнив би і читання прайсу, і
-- редагування в адмінці. Якщо мов колись стане більше — тоді й нормалізуємо.
--
-- Nullable без default: порожнє поле означає «переклад ще не написали», і
-- вітрина в такому разі показує український текст. Порожній рядок за
-- замовчуванням стер би цю різницю — англомовний відвідувач бачив би дірку
-- замість назви послуги.
--
-- Міграція повторювана (`if not exists`): її можна виконати двічі поспіль на
-- тій самій базі без помилки.
alter table services
  add column if not exists title_en   text,
  add column if not exists summary_en text;

alter table kits
  add column if not exists title_en   text,
  add column if not exists summary_en text;
