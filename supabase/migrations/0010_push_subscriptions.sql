-- Підписки на пуш-сповіщення для адмінки-PWA.
--
-- Заявки й замовлення вже їдуть у Telegram (див. lib/notify.ts), і той канал
-- лишається. Але Telegram — окремий застосунок: сповіщення веде в чат, а не в
-- адмінку, і губиться серед решти переписки. Пуш із самої PWA приходить на
-- екран телефону й відкриває потрібний розділ одним тапом.
--
-- Рядок = один пристрій. Майстриня може поставити адмінку і на телефон, і на
-- планшет, тож підписок кілька, і розсилка йде по всіх.
create table push_subscriptions (
  id         uuid primary key default gen_random_uuid(),
  -- Ендпойнт, виданий push-сервісом браузера (FCM, Mozilla, Apple). Він же
  -- ідентифікує пристрій: той самий браузер на тому самому телефоні завжди
  -- дає той самий рядок, тож unique тут ловить повторну підписку.
  endpoint   text not null unique,
  -- Ключі шифрування з PushSubscription. Без них payload не зашифрувати:
  -- push-сервіс бачить лише шифротекст, а розкриває його браузер.
  p256dh     text not null,
  auth       text not null,
  -- Чим підписались — щоб відрізнити телефон від планшета в списку пристроїв.
  user_agent text,
  -- Коли востаннє вдалося достукатись. Оновлюється на кожній успішній
  -- розсилці: за ним видно мертві підписки, які браузер ще не відкликав.
  last_ok_at timestamptz,
  created_at timestamptz not null default now()
);

alter table push_subscriptions enable row level security;

