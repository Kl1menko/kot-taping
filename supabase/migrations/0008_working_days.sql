-- Робочі дні майстрині: які дати відкриті для запису і в якому кабінеті.
--
-- До цієї міграції форма запису приймала будь-яку дату в майбутньому. Клієнтка
-- обирала неділю, коли кабінет зачинений, або київський день, коли майстриня
-- у Львові, — і заявка приходила лише щоб її переузгодили листуванням. Тепер
-- графік задається в адмінці, а форма показує рівно ті дні, які справді
-- відкриті.
--
-- Рядок = один робочий день одного кабінету. Дні, яких у таблиці немає,
-- вважаються неробочими: графік — це білий список, а не чорний. Так «нічого не
-- налаштовано» означає «нічого не відкрито», і жодна дата не проскакує сама.
create table working_days (
  id          uuid primary key default gen_random_uuid(),
  -- FK, а не slug: кабінети — довідник, який не видаляють, а деактивують,
  -- і графік без кабінету сенсу не має. Звідси cascade.
  location_id uuid not null references locations (id) on delete cascade,
  -- Календарна дата в зоні студії (STUDIO_TZ), без часу: майстриня мислить
  -- «субота 8 серпня», а не моментом у UTC.
  day         date not null,
  -- Які проміжки відкриті. Дзеркалять PREFERRED_TIMES з src/lib/intake.ts:
  -- саме їх бачить клієнтка у «Коли зручно». Порожній масив неможливий —
  -- день без жодного проміжку це не робочий день, а його відсутність.
  -- `cardinality`, а не `array_length`: на порожньому масиві другий повертає
  -- NULL, а не 0, і `NULL between 1 and 3` — це NULL. Check-констрейнт відкидає
  -- лише false, тож порожній масив проходив би наскрізь, даючи «робочий день,
  -- у який не можна записатись» — стан, який ця таблиця й має унеможливити.
  slots       text[] not null default '{morning,day,evening}'
                check (
                  cardinality(slots) between 1 and 3
                  and slots <@ array['morning', 'day', 'evening']
                ),
  -- Нотатка для себе: «лише курси», «до 15:00». В адмінці видно, клієнтці ні.
  note        text,
  created_at  timestamptz not null default now(),

  -- Один рядок на кабінет і дату: перемикач, а не журнал змін.
  unique (location_id, day)
);

-- Форма запису питає рівно це: відкриті дні одного кабінету від сьогодні.
create index working_days_location_day_idx on working_days (location_id, day);

alter table working_days enable row level security;

-- Графік бачить і адмінка, і публічна форма — але обидві читають його з
-- сервера під service-role, як і решту таблиць. Policy тут немає навмисно.

-- Дзвіночок адмінці: змінений з іншого пристрою графік має підтягнутись сам.
create trigger working_days_ping
  after insert or update or delete on working_days
  for each statement execute function notify_change();
