-- Анкета запису: канал зв'язку, параметри для матеріалу, згоди.
--
-- Маршрут пацієнта до цієї міграції розривався одразу після заявки: у базу
-- приїжджали ім'я, телефон і дата, а далі майстриня руками вела листування на
-- 1–2 дні, щоб дізнатися колір тейпу, зріст і об'єми та надіслати форму з
-- протипоказаннями. Тепер це приїжджає разом із заявкою.
--
-- Протипоказання питаються ДО запису, а не після. Раніше людина проходила
-- запис і кілька днів очікування, і аж тоді могло виявитися, що процедура їй
-- протипоказана.

-- — Канал зв'язку —
-- Крок 2 маршруту — «знайти пацієнта за ніком або номером». Телефон був
-- єдиним контактом, тож Instagram-нік не було де зберігати.
create type contact_channel as enum ('telegram', 'instagram', 'phone');

alter table requests
  -- Телефон лишається обов'язковим і за нього ж рахується антиспам, а канал
  -- каже, куди саме писати підтвердження.
  add column contact_channel contact_channel not null default 'telegram',
  -- Нік в Instagram/Telegram без «@» — нормалізує застосунок. Для каналу
  -- 'phone' лишається null.
  add column contact_handle  text,

  -- Орієнтовний час дня. Точний час ставить майстриня, коли переносить заявку
  -- в календар: розкладом далі керує вона, а не пацієнт.
  add column preferred_time  text
    check (preferred_time is null or preferred_time in ('morning', 'day', 'evening')),

  -- — Параметри для розрахунку матеріалу (крок 3 маршруту) —
  -- Усі необов'язкові: довга анкета перед записом рубає конверсію зі сторіз,
  -- а лійка тримається на імпульсі «побачив → записався». Хто заповнив —
  -- економить майстрині листування, хто ні — уточнюють у чаті, як і раніше.
  add column tape_color      text,
  -- Сантиметри. Стеля згори — захист від друкарської помилки, а не медична
  -- норма.
  add column height_cm       integer check (height_cm is null or (height_cm between 100 and 250)),
  -- Вільний текст: об'єми пацієнти пишуть як завгодно («талія 68, стегна 95»),
  -- і розбирати це в колонки немає сенсу — читає їх людина.
  add column measurements    text,

  -- — Згоди (крок 6 маршруту, зсунутий на крок 1) —
  -- Відмічені абсолютні протипоказання. Запис не блокується: остаточне
  -- рішення за майстринею, тож заявка приходить із прапорцем «потребує
  -- узгодження», а не зникає.
  add column contraindications text[] not null default '{}',
  -- Момент згоди на обробку даних. Не boolean: для персональних даних треба
  -- знати саме коли, а null тут читається як «згоди не було».
  add column consent_at      timestamptz;

-- Заявки, які треба узгодити перед підтвердженням, — щоб адмінка діставала їх
-- одним запитом, не читаючи всю таблицю.
create index requests_flagged_idx
  on requests (created_at desc)
  where contraindications <> '{}';

comment on column requests.contraindications is
  'Відмічені пацієнтом протипоказання. Не порожньо — заявка потребує узгодження.';
