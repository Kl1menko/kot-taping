-- Точна година в заявці з сайту.
--
-- `requests.preferred_time` зберігав проміжок («вечір») — усе, що форма вміла
-- спитати до появи робочих годин (0011). Тепер клієнтка обирає годину зі
-- сітки, і саме її має бачити майстриня: «17:30», а не «десь після 16-ї».
--
-- Проміжок лишаємо: за ним зручно фільтрувати список заявок, а старі заявки
-- іншого й не мають. Але джерело правди тепер одне — сам час, із якого
-- проміжок і рахується (`slotForTime` у src/lib/schedule.ts).
--
-- Nullable навмисно: заявки, подані до цієї міграції, години не мають, і
-- вигадувати її заднім числом означало б показати майстрині час, якого
-- клієнтка не називала.
alter table requests add column preferred_at time;
