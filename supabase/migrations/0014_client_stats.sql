-- Статистика клієнтів рахується в базі, а не в пам'яті застосунку.
--
-- `listClientsWithStats` тягнула **всю** таблицю візитів на кожне відкриття
-- вкладки «Клієнти» — без ліміту й без фільтра, — щоб порахувати по кожному
-- клієнту чотири числа: скільки візитів, на яку суму, коли був останній і чи
-- є наступний. Самі клієнти при цьому обмежені 500 рядками, а візити ні.
--
-- Поки база молода, це непомітно. Але росте воно назавжди й лінійно: кожен
-- проведений візит назавжди додає рядок, який щоразу їде по мережі в Node,
-- щоб бути згорнутим у лічильник. За кілька років роботи студії це єдина
-- сторінка адмінки, яка гарантовано стане повільною.
--
-- View, а не матеріалізована таблиця й не тригер на `appointments`: цифри
-- мають бути точні в мить читання (майстриня щойно провела візит і одразу
-- дивиться картку), а їх оновлення — не окремий стан, який може розійтися з
-- візитами. Індекс `appointments_client_idx` із 0001 покриває групування.
create or replace view client_stats as
select
  c.id as client_id,
  -- Рахуємо лише проведені: скасований чи запланований візит нічого не каже
  -- ні про суму, ні про те, коли людина була востаннє.
  count(*) filter (where a.status = 'done')                as visits,
  coalesce(sum(a.price) filter (where a.status = 'done'), 0) as total_spent,
  max(a.starts_at) filter (where a.status = 'done')        as last_visit,
  -- Найближчий майбутній запланований — саме той, що показується в списку.
  min(a.starts_at) filter (
    where a.status = 'planned' and a.starts_at >= now()
  )                                                        as next_visit
from clients c
left join appointments a on a.client_id = c.id
group by c.id;

-- Міста клієнта — від найчастішого до рідшого.
--
-- Саме список, а не одне місто: студія працює у Львові й Києві, і людина
-- цілком може бувати в обох (переїзд, відрядження). Показати одне означало б
-- тихо збрехати про друге — тому `array_agg` із сортуванням за частотою.
--
-- Скасовані не рахуються: візит, який не відбувся, нічого не каже про те,
-- куди людина ходить. Заплановані рахуються — щойно створений запис у новому
-- місті теж відповідає на це питання.
create or replace view client_cities as
select
  client_id,
  array_agg(city order by visits desc, city) as cities
from (
  select a.client_id, l.city, count(*) as visits
    from appointments a
    join locations l on l.id = a.location_id
   where a.status <> 'cancelled'
   group by a.client_id, l.city
) ranked
group by client_id;

